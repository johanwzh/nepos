/** @type {'no' | 'en'} */
let current = 'no';

/** @param {string} lang */
export function setLang(lang) {
  current = lang === 'en' ? 'en' : 'no';
}

export function getLang() {
  return current;
}

/**
 * @param {string} key
 * @param {...any} args passed to function-valued texts
 * @returns {string}
 */
export function t(key, ...args) {
  const value = STRINGS[current][key] ?? STRINGS.en[key];
  if (typeof value === 'function') return value(...args);
  return value ?? key;
}
